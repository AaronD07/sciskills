"""Load pack manifests and profiles, and render the router's routing table.

Shared by install.py and lint_skills.py. Standard library only.

Layout:
    packs/<pack>/pack.json            name, description, skills (in routing order)
    packs/<pack>/skills/<skill>/      self-contained skill: SKILL.md, scripts/, references/
    packs/profiles.json               named sets of packs
"""
import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
ROUTER = "sciskills-start-here"
ROUTER_PACK = "core"
ROUTES_START = "<!-- routes:start (generated by scripts/install.py; edit pack.json instead) -->"
ROUTES_END = "<!-- routes:end -->"


def _read_json(path):
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise ValueError(f"{path}: {exc}") from None


def load_packs(root=REPO):
    """Return {pack name: manifest}, each manifest with an added 'dir' Path."""
    packs_root = Path(root) / "packs"
    if not packs_root.is_dir():
        raise ValueError("no packs/ directory")
    packs = {}
    for manifest_path in sorted(packs_root.glob("*/pack.json")):
        data = _read_json(manifest_path)
        where = manifest_path.relative_to(root)
        if not isinstance(data, dict) or not isinstance(data.get("skills"), list):
            raise ValueError(f"{where}: expected an object with a 'skills' list")
        if data.get("name") != manifest_path.parent.name:
            raise ValueError(f"{where}: name must match directory '{manifest_path.parent.name}'")
        if not isinstance(data.get("description"), str) or not data["description"].strip():
            raise ValueError(f"{where}: needs a 'description'")
        for entry in data["skills"]:
            if not isinstance(entry, dict) or not isinstance(entry.get("name"), str):
                raise ValueError(f"{where}: each skill needs a 'name'")
            route = entry.get("route")
            if entry["name"] != ROUTER and not (isinstance(route, str) and route.strip()):
                raise ValueError(f"{where}: skill '{entry['name']}' needs a 'route'")
        data["dir"] = manifest_path.parent
        packs[data["name"]] = data
    if ROUTER_PACK not in packs:
        raise ValueError(f"packs/{ROUTER_PACK}/pack.json is missing")
    return packs


def load_profiles(root=REPO):
    path = Path(root) / "packs" / "profiles.json"
    data = _read_json(path)
    if not isinstance(data, dict):
        raise ValueError(f"{path}: expected an object of profiles")
    for name, profile in data.items():
        if not isinstance(profile, dict) or not isinstance(profile.get("packs"), list):
            raise ValueError(f"{path}: profile '{name}' needs a 'packs' list")
    return data


def skill_path(pack, skill_name):
    return pack["dir"] / "skills" / skill_name


def resolve(packs, profiles, profile=None, names=None, everything=False):
    """Return the ordered pack names selected by exactly one of the three options."""
    if sum(bool(x) for x in (profile, names, everything)) != 1:
        raise ValueError("choose exactly one of --profile, --packs or --all")
    if everything:
        chosen = list(packs)
    elif profile:
        if profile not in profiles:
            raise ValueError(f"unknown profile '{profile}'; options: {', '.join(sorted(profiles))}")
        chosen = profiles[profile]["packs"]
    else:
        chosen = names
    unknown = [n for n in chosen if n not in packs]
    if unknown:
        raise ValueError(f"unknown pack(s): {', '.join(unknown)}")
    # Keep core first so the most general checks lead the routing table.
    ordered = sorted(dict.fromkeys(chosen), key=lambda n: (n != ROUTER_PACK, list(packs).index(n)))
    return ordered


def render_routes(packs, selected):
    lines = ["| The researcher is... | Follow |", "| --- | --- |"]
    for name in selected:
        for entry in packs[name]["skills"]:
            if entry["name"] != ROUTER:
                lines.append(f"| {entry['route']} | `{entry['name']}` |")
    return "\n".join(lines)


def with_routes(router_text, table):
    """Replace the generated region of the router's SKILL.md with `table`."""
    start, end = router_text.find(ROUTES_START), router_text.find(ROUTES_END)
    if start < 0 or end < start:
        raise ValueError(f"router SKILL.md is missing the {ROUTES_START!r} / {ROUTES_END!r} markers")
    return router_text[:start + len(ROUTES_START)] + "\n" + table + "\n" + router_text[end:]
